"""Office formats: Word documents, spreadsheets and presentations.

Three parsers, one container. Each reads the modern Open Packaging Convention
format (``.docx``, ``.xlsx``, ``.pptx``, and their macro-enabled twins) - a zip
of XML parts, whose shared hazards are dealt with in :mod:`app.parsing.archive`
before any library opens the file. The macros in a macro-enabled file are simply
another part in the archive; nothing here executes anything, it reads text.

The LEGACY formats (``.doc``, ``.xls``, ``.ppt``) are a different thing entirely -
OLE2 compound files, not zips - and are NOT supported. They are refused honestly
at upload rather than half-read into garbage.

Each format is split into the units a person would actually cite. A spreadsheet
is one unit per SHEET and a presentation one per SLIDE, so a retrieved passage
can say "Q3 Forecast" or "slide 12" instead of pointing into an undifferentiated
wall of text. A Word document has no such natural seam - its headings are a
formatting convention, not a structure - so it stays one unit and is split by
length downstream, like any long text.

Reading runs in a killable child process (see :mod:`app.parsing.isolation`): the
XML underneath is parsed by lxml, and native code cannot be interrupted in-thread.
"""

from __future__ import annotations

import asyncio
from io import BytesIO
from typing import Any, ClassVar

from app.parsing.archive import (
    DOCX_MARKER,
    PPTX_MARKER,
    XLSX_MARKER,
    check_archive,
    contains_part,
)
from app.parsing.base import DocumentParser, ParsedDocument
from app.parsing.isolation import run_isolated

# Generous for a large document, bounded so a pathological one cannot run forever.
_DEFAULT_PARSE_TIMEOUT_SECONDS = 60.0

# How a spreadsheet row and a table row are laid out as text. A separator keeps
# cells from running together into a single meaningless word, which matters for
# both retrieval and for the model reading the passage back.
_CELL_SEPARATOR = " | "


# A body can nest content controls inside content controls; this bounds the walk
# against a pathological (or hostile) file without touching any real document,
# which never nests them more than a handful deep.
_MAX_SDT_DEPTH = 20


def _read_docx(data: bytes) -> str:
    """Extract a Word document's text in reading order; runs in the child process.

    Walks the body's own children rather than ``document.paragraphs``, because
    that shortcut returns ONLY paragraphs - a document whose content lives in a
    table (a form, a spec sheet, a rate card) or a content control (the fields in
    a template) would come back empty, and the file would look successfully
    ingested while holding nothing. Tables are read in place, so a caption still
    precedes the table it introduces, and content controls are descended into so
    the value a form actually holds is not lost.

    Headers, footers and footnotes are deliberately left out: they repeat on every
    page and would drown the body's own text in the index.
    """
    import docx
    from docx.oxml.ns import qn
    from docx.table import Table
    from docx.text.paragraph import Paragraph

    document = docx.Document(BytesIO(data))
    blocks: list[str] = []

    def walk(container: Any, depth: int) -> None:
        for element in container.iterchildren():
            if element.tag == qn("w:p"):
                text = Paragraph(element, document).text.strip()
                if text:
                    blocks.append(text)
            elif element.tag == qn("w:tbl"):
                for row in Table(element, document).rows:
                    cells = [cell.text.strip() for cell in row.cells]
                    if any(cells):
                        blocks.append(_CELL_SEPARATOR.join(cells))
            elif element.tag == qn("w:sdt") and depth < _MAX_SDT_DEPTH:
                # A content control wraps its block content in an sdtContent child.
                for content in element.iterchildren(qn("w:sdtContent")):
                    walk(content, depth + 1)

    walk(document.element.body, 0)
    return "\n".join(blocks)


def _read_xlsx(data: bytes) -> list[tuple[str, str]]:
    """Extract each sheet as (name, text); runs in the child process.

    ``data_only`` asks for the values Excel last calculated rather than the
    formulas that produce them - "=SUM(B2:B9)" tells a reader nothing, "41,207"
    is the answer they came for. A workbook generated by a program and never
    opened in Excel has no cached values, and those cells read as blank; that is
    a limitation of the file, not of the reader, and it is better than indexing
    formula source as if it were data.

    ``read_only`` streams the sheet instead of building the whole workbook in
    memory, which is what keeps a large spreadsheet from being read at the cost
    of its own size again.
    """
    import openpyxl

    workbook = openpyxl.load_workbook(BytesIO(data), read_only=True, data_only=True)
    try:
        sheets: list[tuple[str, str]] = []
        for worksheet in workbook.worksheets:
            lines: list[str] = []
            for row in worksheet.iter_rows(values_only=True):
                cells = ["" if value is None else str(value).strip() for value in row]
                # Trailing empties are the sheet's padding, not data: a row is as
                # wide as its last real cell, not as wide as the used range.
                while cells and not cells[-1]:
                    cells.pop()
                if any(cells):
                    lines.append(_CELL_SEPARATOR.join(cells))
            sheets.append((worksheet.title, "\n".join(lines)))
        return sheets
    finally:
        workbook.close()


def _shape_text(shape: Any) -> list[str]:
    """Pull the text out of one slide shape, including grouped and tabular ones."""
    blocks: list[str] = []
    # A group is a shape holding shapes; its children carry the text, and a slide
    # built from grouped boxes would otherwise read as empty.
    if hasattr(shape, "shapes"):
        for child in shape.shapes:
            blocks.extend(_shape_text(child))
        return blocks
    if getattr(shape, "has_table", False):
        for row in shape.table.rows:
            cells = [cell.text.strip() for cell in row.cells]
            if any(cells):
                blocks.append(_CELL_SEPARATOR.join(cells))
        return blocks
    if getattr(shape, "has_text_frame", False):
        text = shape.text_frame.text.strip()
        if text:
            blocks.append(text)
    return blocks


def _read_pptx(data: bytes) -> list[str]:
    """Extract each slide's text, in slide order; runs in the child process.

    Speaker notes are included. They are often where the actual argument of a
    slide lives - the slide itself may be three words and a chart - so dropping
    them would throw away the most answerable text in the file.
    """
    from pptx import Presentation

    presentation = Presentation(BytesIO(data))
    slides: list[str] = []
    for slide in presentation.slides:
        blocks: list[str] = []
        for shape in slide.shapes:
            blocks.extend(_shape_text(shape))
        if slide.has_notes_slide:
            notes = slide.notes_slide.notes_text_frame
            if notes is not None and notes.text.strip():
                blocks.append(f"Notes: {notes.text.strip()}")
        slides.append("\n".join(blocks))
    return slides


class _OoxmlParser(DocumentParser):
    """Shared plumbing: check the container, then read it in a killable child."""

    #: The archive part that identifies this format ("word/document.xml").
    marker: ClassVar[str] = ""
    #: What this format is called in a message the uploader reads.
    what: ClassVar[str] = "file"

    def __init__(self, *, timeout_seconds: float = _DEFAULT_PARSE_TIMEOUT_SECONDS) -> None:
        """Create a parser that gives one file ``timeout_seconds`` to be read."""
        self._timeout = timeout_seconds

    def sniff(self, data: bytes) -> bool:
        """Claim a file that IS this format, whatever it was called.

        Every office format looks the same from outside - a zip - so the zip
        signature alone claims nothing. What decides it is which part is inside.
        """
        return contains_part(data, self.marker)


class DocxParser(_OoxmlParser):
    """Reads a Word document as one unit of text, tables included."""

    media_types: ClassVar[frozenset[str]] = frozenset(
        {
            "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
            "application/vnd.ms-word.document.macroenabled.12",
        }
    )
    extensions: ClassVar[frozenset[str]] = frozenset({".docx", ".docm"})
    marker: ClassVar[str] = DOCX_MARKER
    what: ClassVar[str] = "Word document"

    async def parse(
        self, data: bytes, *, filename: str, media_type: str | None = None
    ) -> list[ParsedDocument]:
        """Extract the document's text; an empty document yields nothing.

        Raises:
            ParseFailedError: The file is corrupt, hostile, or too slow to read.
        """
        if not data:
            return []
        # Off the event loop: inspecting the container walks every part, and on a
        # hostile file (many parts, large XML) that is real work that would
        # otherwise stall every other ingest job on the worker.
        await asyncio.to_thread(check_archive, data, what=self.what)
        text = await run_isolated(_read_docx, data, timeout_seconds=self._timeout, what=self.what)
        if not text.strip():
            return []
        # One unit, so the filename is already its name - no title to add.
        return [ParsedDocument(ordinal=0, text=text)]


class XlsxParser(_OoxmlParser):
    """Reads a spreadsheet as one unit per sheet, titled with the sheet's name."""

    media_types: ClassVar[frozenset[str]] = frozenset(
        {
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            "application/vnd.ms-excel.sheet.macroenabled.12",
        }
    )
    extensions: ClassVar[frozenset[str]] = frozenset({".xlsx", ".xlsm"})
    marker: ClassVar[str] = XLSX_MARKER
    what: ClassVar[str] = "spreadsheet"

    async def parse(
        self, data: bytes, *, filename: str, media_type: str | None = None
    ) -> list[ParsedDocument]:
        """Extract each sheet's cells; an empty sheet is skipped, its position kept.

        Raises:
            ParseFailedError: The file is corrupt, hostile, or too slow to read.
        """
        if not data:
            return []
        # Off the event loop: inspecting the container walks every part, and on a
        # hostile file (many parts, large XML) that is real work that would
        # otherwise stall every other ingest job on the worker.
        await asyncio.to_thread(check_archive, data, what=self.what)
        sheets = await run_isolated(_read_xlsx, data, timeout_seconds=self._timeout, what=self.what)
        documents: list[ParsedDocument] = []
        for index, (name, text) in enumerate(sheets):
            if not text.strip():
                continue
            documents.append(ParsedDocument(ordinal=index, text=text, title=name))
        return documents


class PptxParser(_OoxmlParser):
    """Reads a presentation as one unit per slide, notes included."""

    media_types: ClassVar[frozenset[str]] = frozenset(
        {
            "application/vnd.openxmlformats-officedocument.presentationml.presentation",
            "application/vnd.ms-powerpoint.presentation.macroenabled.12",
        }
    )
    extensions: ClassVar[frozenset[str]] = frozenset({".pptx", ".pptm"})
    marker: ClassVar[str] = PPTX_MARKER
    what: ClassVar[str] = "presentation"

    async def parse(
        self, data: bytes, *, filename: str, media_type: str | None = None
    ) -> list[ParsedDocument]:
        """Extract each slide's text; a slide with none is skipped, its number kept.

        A picture-only slide holds no text and is left out rather than indexed as
        blank, but the slides that remain keep their true numbers, so a citation
        still reads "slide 9".

        Raises:
            ParseFailedError: The file is corrupt, hostile, or too slow to read.
        """
        if not data:
            return []
        # Off the event loop: inspecting the container walks every part, and on a
        # hostile file (many parts, large XML) that is real work that would
        # otherwise stall every other ingest job on the worker.
        await asyncio.to_thread(check_archive, data, what=self.what)
        slides = await run_isolated(_read_pptx, data, timeout_seconds=self._timeout, what=self.what)
        documents: list[ParsedDocument] = []
        for index, text in enumerate(slides):
            if not text.strip():
                continue
            documents.append(ParsedDocument(ordinal=index, text=text, title=f"slide {index + 1}"))
        return documents
