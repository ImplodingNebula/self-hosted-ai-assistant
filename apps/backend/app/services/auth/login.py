"""The login round trip: start the consent, then complete the callback.

Two functions, in the order they run. Everything HTTP - the redirect, the
cookie, the problem document - stays in the router; this module decides what
happens and returns plain values.

The authorization request is the ordinary OAuth 2.1 authorization-code flow with
PKCE plus OIDC's ``nonce``, and both of its secrets are generated by the shared
helpers in :mod:`app.services.oauth.authorize` rather than reimplemented here.
What each one defends is worth restating, because they are easy to mistake for
duplicates of each other:

- ``state`` binds the callback to a login THIS backend started, and is
  single-use so a captured callback URL cannot be replayed.
- ``code_verifier`` (PKCE) binds the code to the process that requested it, so
  an intercepted code cannot be exchanged by anybody else.
- ``nonce`` binds the returned id_token to this attempt, so a token obtained
  elsewhere cannot be injected into this callback.

The ``next`` parameter is the one piece of caller-supplied data that survives
the round trip, and it is restricted to a RELATIVE PATH. An absolute or
scheme-bearing value would make this endpoint an open redirector attached to a
sign-in - the most credible phishing hop a site can offer.
"""

