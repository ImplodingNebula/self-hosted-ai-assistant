# The path the provider returns to. Relative to OAUTH_REDIRECT_BASE_URL, which
# is the deployment's ONE public-origin knob - the same value the integrations
# consent flow returns through, because a deployment has one public origin, not
# one per feature.
CALLBACK_PATH = "/api/v1/auth/callback"

# The minimum OIDC scope set: an id_token at all, plus the address admission is
# decided on. Nothing wider is requested - this flow wants an identity, not
# access to anything the person owns at the provider.
LOGIN_SCOPES = ("openid", "email", "profile")

# A token exchange is one small POST to an operator-configured provider. Kept
# short because a person is watching a blank redirect page while it runs.
TOKEN_EXCHANGE_TIMEOUT_SECONDS = 10.0

_DEFAULT_NEXT = "/"

# Characters a landing path may never contain: every C0 control (which includes
# the tab, CR and LF a browser strips before parsing), DEL, and the backslash
# some browsers normalize into an authority separator. See :func:`safe_next_path`
# for why this is a rejection list rather than something the URL parser is
# trusted to handle.
_FORBIDDEN_NEXT_CHARACTERS = frozenset({chr(code) for code in range(0x20)} | {"\x7f", "\\"})


def redirect_uri(settings: Settings) -> str:
    """The callback URL registered with the provider."""
    return f"{settings.oauth_redirect_base_url.rstrip('/')}{CALLBACK_PATH}"


def safe_next_path(value: str | None) -> str:
    """Reduce a caller-supplied ``next`` to a relative path, or the default.

    A sign-in endpoint that will redirect anywhere is an open redirector wearing
    the most trustworthy hat on the site, so anything that is not plainly a path
    on this origin is DISCARDED rather than corrected - silently rewriting a
    hostile value only invites trying the next encoding of it.

    Four rules, and the third is the one that is easy to get wrong:

    1. It must begin with a single ``/`` - no scheme, no authority.
    2. It must not begin with ``//``, which a browser reads as
       protocol-relative and therefore as another origin.
    3. It must contain NO C0 control character, DEL, or backslash. This is not
       belt-and-braces: **browsers strip tab, CR and LF out of a URL before
       parsing it**, so ``/<tab>/evil.example`` inspects here as a perfectly
       ordinary relative path and arrives at the browser as ``//evil.example``.
       Any check that reasons about the string as-written is bypassed by it.
       (Backslash is in the same family - some browsers normalize it into an
       authority separator.) Rejecting the characters outright is the only
       version of this check that cannot be walked around, and it must not
       depend on a parser incidentally stripping them: CPython's ``urlsplit``
       happens to drop tab/CR/LF today, which makes a test written against
       those three pass for a reason that is not the guard, while a NUL and
       the rest of C0 sail straight through.
    4. After all that it must still parse with no scheme and no netloc.

    Args:
        value: The raw ``?next=`` value, or None.

    Returns:
        A path beginning with a single ``/``, or ``"/"``.
    """
    if not value:
        return _DEFAULT_NEXT
    candidate = value.strip()
    if not candidate.startswith("/"):
        return _DEFAULT_NEXT
    if candidate.startswith("//"):
        return _DEFAULT_NEXT
    if any(character in _FORBIDDEN_NEXT_CHARACTERS for character in candidate):
        return _DEFAULT_NEXT
    parts = urlsplit(candidate)
    if parts.scheme or parts.netloc:
        return _DEFAULT_NEXT
    return candidate


@dataclass(frozen=True, slots=True)
class StartedLogin:
    """Where to send the browser, and the state the callback will consume."""

    authorization_url: str
    state: str


async def start_login(
    *,
    settings: Settings,
    store: KeyValueStore,
    next_path: str | None = None,
    http_client: httpx.AsyncClient | None = None,
) -> StartedLogin:
    """Begin a sign-in: stash the pending state and build the consent URL.

    Args:
        settings: The deployment's configuration; login must be enabled.
        store: Where the pending state is held until the callback.
        next_path: The caller's requested landing path, sanitised here.
        http_client: Injected for tests; otherwise one is built and closed.

    Returns:
        The provider URL to redirect to, and the state that names this attempt.

    Raises:
        LoginConfigurationError: Login is not configured, or the issuer's
            metadata could not be resolved.
    """
    if not settings.oidc_enabled or settings.oidc_client_id is None:
        raise LoginConfigurationError("login is not configured on this deployment")

    client = http_client or httpx.AsyncClient(timeout=DISCOVERY_TIMEOUT_SECONDS)
    try:
        metadata = await discover_provider(str(settings.oidc_issuer), client=client)
    finally:
        if http_client is None:
            await client.aclose()

    state = generate_state()
    nonce = generate_state()
    verifier = generate_pkce_verifier()
    await put_pending(
        store,
        state,
        PendingLogin(nonce=nonce, code_verifier=verifier, next_path=safe_next_path(next_path)),
    )

    url = build_authorization_url(
        # send_resource=False: RFC 8707 binds a token to the MCP server it was
        # requested for; a login is not requesting access to a resource at all,
        # and providers reject the parameter they do not implement.
        OAuthEndpoints(
            issuer=metadata.issuer,
            authorization_endpoint=metadata.authorization_endpoint,
            token_endpoint=metadata.token_endpoint,
            send_resource=False,
        ),
        client_id=settings.oidc_client_id,
        redirect_uri=redirect_uri(settings),
        scopes=LOGIN_SCOPES,
        state=state,
        code_challenge=pkce_challenge(verifier),
        extra_params={"nonce": nonce},
    )
    return StartedLogin(authorization_url=url, state=state)


@dataclass(frozen=True, slots=True)
class CompletedLogin:
    """The signed-in user and where the browser should land."""

    user: User
    next_path: str


async def complete_login(
    *,
    code: str,
    state: str,
    settings: Settings,
    store: KeyValueStore,
    session: AsyncSession,
    jwks: JwksCache | None = None,
    http_client: httpx.AsyncClient | None = None,
) -> CompletedLogin:
    """Finish a sign-in: consume the state, verify the token, resolve the user.

    Args:
        code: The authorization code from the provider.
        state: The state value the provider echoed back.
        settings: The deployment's configuration.
        store: Where the pending state was stashed.
        session: An open database session; the CALLER commits.
        jwks: The signing-key cache; the process-wide one by default.
        http_client: Injected for tests; otherwise one is built and closed.

    Returns:
        The resolved user and the sanitised landing path.

    Raises:
        LoginConfigurationError: Login is not configured or the provider is not
            usable.
        LoginProtocolError: The state was unknown, expired or already used, or
            the token failed any verification check.
        AdmissionDeniedError: The identity is genuine and not admitted here.
    """
    if not settings.oidc_enabled or settings.oidc_client_id is None:
        raise LoginConfigurationError("login is not configured on this deployment")

    # Consumed FIRST and ATOMICALLY: a second callback bearing the same state -
    # a replay, or the same code injected twice - finds nothing here, before any
    # network call is made on its behalf.
    pending = await take_pending(store, state)
    if pending is None:
        raise LoginProtocolError("this sign-in link has expired or was already used")
    # The landing path was validated when it was stashed, and it is re-validated
    # on the way out. Not because the store is untrusted, but because this is the
    # value that becomes a redirect: one guard at the far end of the round trip
    # means no future writer of a pending record can reopen the redirector, and
    # it costs a string check.
    landing = safe_next_path(pending.next_path)

    client = http_client or httpx.AsyncClient(timeout=TOKEN_EXCHANGE_TIMEOUT_SECONDS)
    try:
        metadata = await discover_provider(str(settings.oidc_issuer), client=client)
        id_token = await _exchange_code(
            code,
            verifier=pending.code_verifier,
            token_endpoint=metadata.token_endpoint,
            settings=settings,
            client=client,
        )
        identity = await verify_id_token(
            id_token,
            # The issuer the PROVIDER declares, not the one an operator typed.
            # The token's ``iss`` is compared exactly, and a provider's canonical
            # spelling may carry a trailing slash the operator did not write (or
            # omit one they did) - Auth0's is ``https://tenant.auth0.com/``, so
            # comparing against the configured string refuses every real token
            # from it, and the coarse refusal page gives nobody a clue why.
            # Discovery has already proven the two name the same issuer, so
            # taking the declared form loses no check and gains the provider's
            # own spelling. It is also what the stored identity key records, so
            # that key stays stable when somebody edits a slash into .env.
            issuer=metadata.issuer,
            client_id=settings.oidc_client_id,
            nonce=pending.nonce,
            jwks_uri=metadata.jwks_uri,
            jwks=jwks or default_jwks_cache(),
            client=client,
        )
    finally:
        if http_client is None:
            await client.aclose()

    if not is_admitted(identity.email, settings=settings):
        # Logged without the address: a refusal line naming every address that
        # tried to sign in turns the log into a list of who is interested in
        # this deployment. The count is what an operator actually needs.
        logger.info("auth.admission_denied issuer=%s", identity.issuer)
        raise AdmissionDeniedError("This account is not permitted to use this workspace.")

    user = await resolve_or_create(session, identity, settings=settings)
    return CompletedLogin(user=user, next_path=landing)


async def _exchange_code(
    code: str,
    *,
    verifier: str,
    token_endpoint: str,
    settings: Settings,
    client: httpx.AsyncClient,
) -> str:
    """Trade the authorization code for an id_token.

    The access token in the response is deliberately ignored and never stored:
    this flow wants to know WHO signed in, not to act at the provider on their
    behalf. Keeping a token nothing calls would be a credential held for no
    reason - which is the definition of an unnecessary breach.
    """
    form = {
        "grant_type": "authorization_code",
        "code": code,
        "redirect_uri": redirect_uri(settings),
        "client_id": settings.oidc_client_id or "",
        "client_secret": settings.oidc_client_secret or "",
        "code_verifier": verifier,
    }
    try:
        # Streamed under the byte cap, like every other remote document here:
        # the response size is the provider's choice and this process also
        # serves every live chat stream.
        async with client.stream(
            "POST",
            token_endpoint,
            data=form,
            headers={"Accept": "application/json"},
            follow_redirects=False,
        ) as response:
            if response.status_code != 200:
                # The body is NOT read into the message: a failed exchange can
                # echo the request back, and the request carries the client
                # secret and the code.
                raise LoginProtocolError(
                    f"the provider refused the sign-in (HTTP {response.status_code})"
                )
            body = await read_capped(response, what="token response")
    except OversizedResponseError as exc:
        raise LoginConfigurationError("the provider's token response was oversized") from exc
    except LoginProtocolError:
        raise
    except httpx.HTTPError as exc:
        raise LoginConfigurationError("the provider's token endpoint could not be reached") from exc

    try:
        payload = json.loads(body)
    except ValueError as exc:
        raise LoginConfigurationError("the provider's token response was not JSON") from exc
    id_token = payload.get("id_token") if isinstance(payload, dict) else None
    if not isinstance(id_token, str) or not id_token:
        raise LoginConfigurationError("the provider's token response carried no id_token")
    return id_token
